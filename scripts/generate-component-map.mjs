#!/usr/bin/env node
/**
 * Generate Component Map for Dynamic Routing
 * 
 * This script auto-generates the COMPONENT_MAP in app/[slug]/page.tsx
 * by reading src/routes.config.ts.
 * 
 * Run after adding new supplements: node scripts/generate-component-map.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const projectRoot = join(__dirname, '..');

// Read routes.config.ts
const routesConfigPath = join(projectRoot, 'src', 'routes.config.ts');
const routesContent = readFileSync(routesConfigPath, 'utf-8');

// Extract all routes from KNOWLEDGEBASE_ROUTES (includes comparison pages)
const supplementRoutes = [];
const comparisonRoutes = [];

// Parse KNOWLEDGEBASE_ROUTES
const knowledgebaseMatch = routesContent.match(/export const KNOWLEDGEBASE_ROUTES:\s*RouteConfig\[\]\s*=\s*\[([\s\S]*?)\n\];\s*(?:export|\/\/)/);
if (knowledgebaseMatch) {
  const routesArrayContent = knowledgebaseMatch[1];
  
  // Extract all component names with their category
  const routePattern = /{\s*[\s\S]*?componentName:\s*['"]([^'"]+)['"][\s\S]*?category:\s*['"]([^'"]+)['"][\s\S]*?}/g;
  let match;
  
  while ((match = routePattern.exec(routesArrayContent)) !== null) {
    const componentName = match[1];
    const category = match[2];
    
    if (category === 'knowledgebase') {
      supplementRoutes.push(componentName);
    } else if (category === 'comparison') {
      comparisonRoutes.push(componentName);
    }
  }
}

console.log(`Found ${supplementRoutes.length} supplement components`);
console.log(`Found ${comparisonRoutes.length} comparison components`);

// Generate imports
const supplementImports = supplementRoutes
  .map(name => `import { ${name} } from '@/components/pages/supplements/${name}';`)
  .join('\n');

const comparisonImports = comparisonRoutes
  .map(name => `  ${name},`)
  .join('\n');

// Generate component map entries
const supplementMapEntries = supplementRoutes
  .map(name => `  '${name}': ${name},`)
  .join('\n');

const comparisonMapEntries = comparisonRoutes
  .map(name => `  '${name}': ${name},`)
  .join('\n');

// Generate the new file content
const newContent = `import { notFound } from 'next/navigation';
import { Metadata } from 'next';
import { getSupplementRoutes, getRouteByPath } from '../lib/route-adapter';
import { getSEOContent } from '@/lib/seo-content';
import { PageViewTracker } from '../components/PageViewTracker';

/**
 * AUTO-GENERATED COMPONENT IMPORTS
 * 
 * This file is automatically generated by scripts/generate-component-map.mjs
 * Run: npm run generate:component-map
 * 
 * DO NOT EDIT MANUALLY - Changes will be overwritten!
 * 
 * To add a new supplement:
 * 1. Add route to src/routes.config.ts
 * 2. Create component file
 * 3. Run: npm run generate:component-map
 * 4. Rebuild: npm run build
 */

// Supplement page components
${supplementImports}

// Comparison page components
import {
${comparisonImports}
} from '@/components/pages/comparisons';

/**
 * Component Map
 * 
 * Maps componentName from routes.config.ts to actual component.
 * Auto-generated from routes.config.ts.
 */
const COMPONENT_MAP: Record<string, React.ComponentType<any>> = {
  // Knowledgebase pages (${supplementRoutes.length})
${supplementMapEntries}
  
  // Comparison pages (${comparisonRoutes.length})
${comparisonMapEntries}
};

interface PageProps {
  params: Promise<{
    slug: string;
  }>;
}

// Generate static params for all supplement pages
export async function generateStaticParams() {
  const routes = getSupplementRoutes();
  
  return routes.map(route => ({
    slug: route.path.replace(/^\\//, '').replace(/\\/\$/, '')
  }));
}

// Generate metadata for each page
export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { slug } = await params;
  const route = getRouteByPath(\`/\${slug}\`);
  
  if (!route) {
    return {
      title: 'Page Not Found',
    };
  }
  
  // Get SEO-optimized content if available
  const seoContent = getSEOContent(route.key);
  
  const baseUrl = process.env.NEXT_PUBLIC_SITE_URL || 'https://www.suppl.me';
  const fullUrl = \`\${baseUrl}\${route.path}\`;
  
  // Use SEO title and description if available, otherwise fall back to route data
  const title = seoContent ? \`\${seoContent.title} | Suppl.me\` : \`\${route.title} - Suppl.me\`;
  const description = seoContent ? seoContent.description : (route.description || \`Evidence-based information about \${route.title} supplements: benefits, dosing, safety, and retailer comparison.\`);
  const keywords = seoContent ? seoContent.keywords.join(', ') : \`\${route.title}, \${route.title.toLowerCase()} supplements, \${route.title.toLowerCase()} benefits, \${route.title.toLowerCase()} dosage, supplement research\`;
  
  return {
    title,
    description,
    keywords,
    authors: [{ name: 'Suppl.me Research Team' }],
    openGraph: {
      title: seoContent ? seoContent.title : route.title,
      description,
      url: fullUrl,
      siteName: 'Suppl.me',
      type: 'article',
      images: [
        {
          url: \`\${baseUrl}/images/og-\${slug}.jpg\`,
          width: 1200,
          height: 630,
          alt: \`\${seoContent ? seoContent.name : route.title} supplement information\`,
        },
      ],
    },
    twitter: {
      card: 'summary_large_image',
      title: seoContent ? seoContent.title : route.title,
      description,
      images: [\`\${baseUrl}/images/og-\${slug}.jpg\`],
    },
    alternates: {
      canonical: fullUrl,
    },
  };
}

// Main page component
export default async function SupplementPage({ params }: PageProps) {
  const { slug } = await params;
  
  // Find the route for this slug
  const route = getRouteByPath(\`/\${slug}\`);
  
  if (!route) {
    notFound();
  }
  
  // Get the component from the auto-generated map
  const Component = COMPONENT_MAP[route.componentName];
  
  if (!Component) {
    console.error(\`Component \${route.componentName} not found in COMPONENT_MAP\`);
    console.error(\`Available components: \${Object.keys(COMPONENT_MAP).join(', ')}\`);
    notFound();
  }
  
  // Render the component
  return (
    <>
      <PageViewTracker pageName={route.title} pageCategory="supplement" />
      <Component />
    </>
  );
}
`;

// Write to app/[slug]/page.tsx
const pagePath = join(projectRoot, 'app', '[slug]', 'page.tsx');
writeFileSync(pagePath, newContent, 'utf-8');

console.log('\n✅ Component map generated successfully!');
console.log(`📝 Updated: app/[slug]/page.tsx`);
console.log(`📊 Total components: ${supplementRoutes.length + comparisonRoutes.length}`);
console.log('\n💡 To use: npm run build');
